// RT-677: the Backend-Core contract pin lives in contracts/backend-core/PIN, in
// the same grammar as POS (RT-217), so one parser serves both consumers.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, expect, test } from "vitest";
import { OPENAPI_SOURCE_SPECS } from "../../openapi-ts.config.ts";
import { comparePinFiles, formatPin, parsePin } from "../../src/lib/contracts-pin.ts";

const OPENAPI_ROOT = "packages/contracts/openapi";

// Verbatim copy of POS `contracts/backend-core/PIN` (RT-217) at c6360f3.
const POS_PIN_FIXTURE = `# Backend-Core OpenAPI contracts vendored for the POS contract-conformance suite
# (tests/contract/backend-core, RT-217). Generated by \`npm run contracts:repin\`.
# Do not hand-edit: the suite checks every file below against its git blob SHA.
repo: Kemetra/Backend-Core
commit: c6360f3d83ea1eef0c2fbb31a9254e85d03f8de6
source: packages/contracts/openapi
file: catalog/read-down.yaml bd8e3abf4f02760d267bc74efc72c7e6ebd72768
file: pos-cashier-admissions.openapi.yaml aec995a5b3ca23071e97c49d00666d19eb3ab4b0
file: pos-operators.openapi.yaml afda13c78d545bcdb218a531a86a7bf33045f6bd
file: pos-payments/vouchers.yaml 2c49388f4a5e2e26fad4b29651f6ccb938859e54
file: pos-sales/sale-history.yaml 8457ef2ded8826ac61568230d92faa450c40fe77
file: pos-sales/sales.yaml 8e4b76862504121130efadbf24ddc6309aea5fa7
file: pos-shifts.openapi.yaml aa25f93375fa5486d5551c0a21225eb671aaa8b8
file: pos-terminal-pairing.openapi.yaml 6a52e32b48ea9385294a16edbf762e5daf7db1a0
`;

// A Windows checkout with core.autocrlf rewrites line endings; the grammar is LF.
const committedPin = (): string =>
  readFileSync(join(process.cwd(), "contracts/backend-core/PIN"), "utf8").replace(/\r\n/g, "\n");

describe("contracts PIN", () => {
  test("parsePin parses the POS PIN fixture", () => {
    const pin = parsePin(POS_PIN_FIXTURE);
    expect(pin.repo).toBe("Kemetra/Backend-Core");
    expect(pin.commit).toBe("c6360f3d83ea1eef0c2fbb31a9254e85d03f8de6");
    expect(pin.source).toBe(OPENAPI_ROOT);
    expect(pin.files).toHaveLength(8);
    expect(pin.files[3]).toEqual({
      path: "pos-payments/vouchers.yaml",
      blobSha: "2c49388f4a5e2e26fad4b29651f6ccb938859e54",
    });
  });

  test("PIN file lists exactly the OPENAPI_SOURCE_SPECS paths", () => {
    const pinned = parsePin(committedPin());
    expect(pinned.repo).toBe("Kemetra/Backend-Core");
    expect(pinned.source).toBe(OPENAPI_ROOT);
    const fromPin = pinned.files.map((f) => f.path).sort();
    const fromSpecs = OPENAPI_SOURCE_SPECS.map((s) =>
      s.path.replace(`${OPENAPI_ROOT}/`, ""),
    ).sort();
    expect(fromPin).toEqual(fromSpecs);
  });

  test("no composed source holds its own pin, so the single-commit PIN describes all of them", () => {
    expect(OPENAPI_SOURCE_SPECS.filter((s) => s.pin !== undefined)).toEqual([]);
  });

  test("formatPin(parsePin(x)) round-trips the committed PIN", () => {
    const text = committedPin();
    expect(formatPin(parsePin(text))).toBe(text);
  });

  test("comparePinFiles reports mismatched, missing and extra entries", () => {
    const a = { path: "a.yaml", blobSha: "a".repeat(40) };
    const b = { path: "b.yaml", blobSha: "b".repeat(40) };
    expect(comparePinFiles([a, b], [b, a])).toEqual([]);
    expect(comparePinFiles([a], [{ ...a, blobSha: "c".repeat(40) }])).toEqual([
      `a.yaml: PIN has blob ${"a".repeat(40)} but Backend-Core has ${"c".repeat(40)}`,
    ]);
    expect(comparePinFiles([a], [a, b])).toEqual([
      "b.yaml: composed by the generator but not listed in the PIN",
    ]);
    expect(comparePinFiles([a, b], [a])).toEqual([
      "b.yaml: listed in the PIN but not composed by the generator",
    ]);
  });

  test("parsePin rejects malformed PIN files", () => {
    const base = POS_PIN_FIXTURE.split("\n").slice(0, 6).join("\n");
    expect(() => parsePin(`${base}\nfile: a.yaml nothex`)).toThrow(/malformed file line/);
    expect(() => parsePin(`${base}\nfile: ../a.yaml ${"a".repeat(40)}`)).toThrow(/unsafe/);
    expect(() => parsePin(`${base}\nbogus: x`)).toThrow(/unknown key/);
    expect(() => parsePin(base)).toThrow(/no files pinned/);
    expect(() => parsePin(POS_PIN_FIXTURE.replace(/commit: \w+/, "commit: abc123"))).toThrow(
      /full SHA/,
    );
    const dup = `file: a.yaml ${"a".repeat(40)}`;
    expect(() => parsePin(`${base}\n${dup}\n${dup}`)).toThrow(/duplicate/);
  });
});
